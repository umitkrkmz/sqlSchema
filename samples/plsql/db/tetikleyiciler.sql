  CREATE OR REPLACE EDITIONABLE TRIGGER "TEL"."TRG_ABONE_DURUM_AU"
  AFTER UPDATE OF DURUM ON "TEL"."ABONE"
  FOR EACH ROW
BEGIN
  INSERT INTO TEL.ABONE_TARIHCE (TARIHCE_ID, ABONE_ID, ESKI_DURUM, YENI_DURUM, DEGISIM_ZAMANI)
  VALUES (TEL.SEQ_TARIHCE.NEXTVAL, :NEW.ABONE_ID, :OLD.DURUM, :NEW.DURUM, SYSTIMESTAMP);
  IF :NEW.DURUM = 'P' THEN
    BILDIRIM_PKG.KUYRUGA_EKLE(:NEW.ABONE_ID, 'SMS', 'Hattınız pasife alındı.');
  END IF;
END;
/
ALTER TRIGGER "TEL"."TRG_ABONE_DURUM_AU" ENABLE;

  CREATE OR REPLACE EDITIONABLE TRIGGER "TEL"."TRG_ODEME_AI"
  AFTER INSERT ON "TEL"."ODEME"
  FOR EACH ROW
DECLARE
  PRAGMA AUTONOMOUS_TRANSACTION;
BEGIN
  TAHSILAT_PKG.MAHSUP(:NEW.ODEME_ID);
  COMMIT;
END;
/
ALTER TRIGGER "TEL"."TRG_ODEME_AI" ENABLE;

  CREATE OR REPLACE EDITIONABLE TRIGGER "TEL"."TRG_MUSTERI_BI"
  BEFORE INSERT ON "TEL"."MUSTERI"
  FOR EACH ROW
BEGIN
  IF :NEW.MUSTERI_ID IS NULL THEN
    :NEW.MUSTERI_ID := TEL.SEQ_MUSTERI.NEXTVAL;
  END IF;
  ENTEGRASYON_PKG.MUSTERI_AKTAR(:NEW.MUSTERI_ID);
END;
/
ALTER TRIGGER "TEL"."TRG_MUSTERI_BI" ENABLE;
