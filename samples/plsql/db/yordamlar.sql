CREATE OR REPLACE EDITIONABLE PROCEDURE "TEL"."GUNLUK_KAPANIS" AS
BEGIN
  IF ORTAK.TARIH_PKG.IS_GUNU_MU(SYSDATE) THEN
    BATCH_PKG.GECE_ISI;
  END IF;
  BILDIRIM_PKG.GONDER;
END GUNLUK_KAPANIS;
/

CREATE OR REPLACE EDITIONABLE FUNCTION "TEL"."ABONE_OZETI" (P_MSISDN IN VARCHAR2) RETURN VARCHAR2 AS
  V_ABONE NUMBER;
BEGIN
  V_ABONE := ABONE_PKG.BUL(P_MSISDN);
  RETURN 'Abone ' || V_ABONE || ', borç ' || TAHSILAT_PKG.BORC(V_ABONE);
END ABONE_OZETI;
/
