-- ACENTE modülü tabloları
-- Not: bütünlük uygulama katmanında; veritabanında FK tanımlı değildir.

-- ACENTE : Satış kanalı: acente
CREATE TABLE SGR.ACENTE
(
  ACENTE_KOD               VARCHAR2(10 CHAR) NOT NULL,
  UNVAN                    VARCHAR2(250 CHAR) NOT NULL,
  VKN                      VARCHAR2(10 CHAR),
  LEVHA_NO                 VARCHAR2(20 CHAR),
  BOLGE_KOD                VARCHAR2(10 CHAR),
  SUBE_KOD                 VARCHAR2(10 CHAR),
  BASLANGIC_TAR            DATE,
  FESIH_TAR                DATE,
  KAYIT_TAR                DATE DEFAULT SYSDATE NOT NULL,
  KAYIT_KULLANICI          VARCHAR2(30 CHAR),
  GUNCELLEME_TAR           DATE
)
TABLESPACE TS_SGR_DATA;
ALTER TABLE SGR.ACENTE ADD CONSTRAINT ACENTE_PK PRIMARY KEY (ACENTE_KOD) USING INDEX TABLESPACE TS_SGR_IDX;
COMMENT ON TABLE SGR.ACENTE IS 'Satış kanalı: acente';

-- ACENTE_YETKI : Acentenin satabileceği branşlar
CREATE TABLE SGR.ACENTE_YETKI
(
  ACENTE_KOD               VARCHAR2(10 CHAR) NOT NULL,
  BRANS_KOD                VARCHAR2(10 CHAR) NOT NULL,
  YETKI_TAR                DATE NOT NULL,
  KAYIT_TAR                DATE DEFAULT SYSDATE NOT NULL,
  KAYIT_KULLANICI          VARCHAR2(30 CHAR),
  GUNCELLEME_TAR           DATE
)
TABLESPACE TS_SGR_DATA;
ALTER TABLE SGR.ACENTE_YETKI ADD CONSTRAINT ACENTE_YETKI_PK PRIMARY KEY (ACENTE_KOD, BRANS_KOD) USING INDEX TABLESPACE TS_SGR_IDX;
COMMENT ON TABLE SGR.ACENTE_YETKI IS 'Acentenin satabileceği branşlar';

-- ACENTE_KOMISYON : Ürün bazında komisyon oranı
CREATE TABLE SGR.ACENTE_KOMISYON
(
  ACENTE_KOD               VARCHAR2(10 CHAR) NOT NULL,
  URUN_KOD                 VARCHAR2(10 CHAR) NOT NULL,
  GECERLILIK_TAR           DATE NOT NULL,
  KOMISYON_ORAN            NUMBER(9,6) NOT NULL,
  KAYIT_TAR                DATE DEFAULT SYSDATE NOT NULL,
  KAYIT_KULLANICI          VARCHAR2(30 CHAR),
  GUNCELLEME_TAR           DATE
)
TABLESPACE TS_SGR_DATA;
ALTER TABLE SGR.ACENTE_KOMISYON ADD CONSTRAINT ACENTE_KOMISYON_PK PRIMARY KEY (ACENTE_KOD, URUN_KOD, GECERLILIK_TAR) USING INDEX TABLESPACE TS_SGR_IDX;
COMMENT ON TABLE SGR.ACENTE_KOMISYON IS 'Ürün bazında komisyon oranı';

-- ACENTE_HAKEDIS : Aylık hakediş
CREATE TABLE SGR.ACENTE_HAKEDIS
(
  HAKEDIS_NO               NUMBER(12,0) NOT NULL,
  ACENTE_KOD               VARCHAR2(10 CHAR) NOT NULL,
  DONEM                    VARCHAR2(6 CHAR) NOT NULL,
  BRUT_TUTAR               NUMBER(18,2),
  STOPAJ_TUTAR             NUMBER(18,2),
  NET_TUTAR                NUMBER(18,2),
  ODEME_TAR                DATE,
  KAYIT_TAR                DATE DEFAULT SYSDATE NOT NULL,
  KAYIT_KULLANICI          VARCHAR2(30 CHAR),
  GUNCELLEME_TAR           DATE
)
TABLESPACE TS_SGR_DATA;
ALTER TABLE SGR.ACENTE_HAKEDIS ADD CONSTRAINT ACENTE_HAKEDIS_PK PRIMARY KEY (HAKEDIS_NO) USING INDEX TABLESPACE TS_SGR_IDX;
COMMENT ON TABLE SGR.ACENTE_HAKEDIS IS 'Aylık hakediş';

-- BROKER
CREATE TABLE SGR.BROKER
(
  BROKER_KOD               VARCHAR2(10 CHAR) NOT NULL,
  UNVAN                    VARCHAR2(250 CHAR) NOT NULL,
  VKN                      VARCHAR2(10 CHAR),
  KAYIT_TAR                DATE DEFAULT SYSDATE NOT NULL,
  KAYIT_KULLANICI          VARCHAR2(30 CHAR),
  GUNCELLEME_TAR           DATE
)
TABLESPACE TS_SGR_DATA;
ALTER TABLE SGR.BROKER ADD CONSTRAINT BROKER_PK PRIMARY KEY (BROKER_KOD) USING INDEX TABLESPACE TS_SGR_IDX;
