-- PRIM_TAHAKKUK : Prim tahakkuku
CREATE TABLE SGR.PRIM_TAHAKKUK
(
  TAHAKKUK_NO              NUMBER(12,0) NOT NULL,
  POLICE_NO                NUMBER(12,0) NOT NULL,
  ZEYL_NO                  NUMBER(4,0) NOT NULL,
  TAKSIT_NO                NUMBER(2,0) NOT NULL,
  VADE_TAR                 DATE NOT NULL,
  TUTAR                    NUMBER(18,2) NOT NULL,
  KALAN_TUTAR              NUMBER(18,2) NOT NULL,
  KAYIT_TAR                DATE DEFAULT SYSDATE NOT NULL,
  KAYIT_KULLANICI          VARCHAR2(30 CHAR),
  GUNCELLEME_TAR           DATE
)
TABLESPACE TS_SGR_DATA;
ALTER TABLE SGR.PRIM_TAHAKKUK ADD CONSTRAINT PRIM_TAHAKKUK_PK PRIMARY KEY (TAHAKKUK_NO) USING INDEX TABLESPACE TS_SGR_IDX;
COMMENT ON TABLE SGR.PRIM_TAHAKKUK IS 'Prim tahakkuku';

