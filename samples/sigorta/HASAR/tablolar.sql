-- HASAR modülü tabloları
-- Not: bütünlük uygulama katmanında; veritabanında FK tanımlı değildir.

-- EKSPER
CREATE TABLE SGR.EKSPER
(
  EKSPER_KOD               VARCHAR2(10 CHAR) NOT NULL,
  AD_SOYAD                 VARCHAR2(100 CHAR) NOT NULL,
  SICIL_BELGE_NO           VARCHAR2(20 CHAR),
  IL_KOD                   VARCHAR2(10 CHAR),
  KAYIT_TAR                DATE DEFAULT SYSDATE NOT NULL,
  KAYIT_KULLANICI          VARCHAR2(30 CHAR),
  GUNCELLEME_TAR           DATE
)
TABLESPACE TS_SGR_DATA;
ALTER TABLE SGR.EKSPER ADD CONSTRAINT EKSPER_PK PRIMARY KEY (EKSPER_KOD) USING INDEX TABLESPACE TS_SGR_IDX;

