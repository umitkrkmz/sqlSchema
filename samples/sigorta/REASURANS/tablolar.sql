-- REASURANS modülü tabloları
-- Not: bütünlük uygulama katmanında; veritabanında FK tanımlı değildir.

-- REASUROR : Reasürans şirketi
CREATE TABLE SGR.REASUROR
(
  REASUROR_KOD             VARCHAR2(10 CHAR) NOT NULL,
  UNVAN                    VARCHAR2(250 CHAR) NOT NULL,
  ULKE_KOD                 VARCHAR2(2 CHAR),
  RATING                   VARCHAR2(5 CHAR),
  KAYIT_TAR                DATE DEFAULT SYSDATE NOT NULL,
  KAYIT_KULLANICI          VARCHAR2(30 CHAR),
  GUNCELLEME_TAR           DATE
)
TABLESPACE TS_SGR_DATA;
ALTER TABLE SGR.REASUROR ADD CONSTRAINT REASUROR_PK PRIMARY KEY (REASUROR_KOD) USING INDEX TABLESPACE TS_SGR_IDX;
COMMENT ON TABLE SGR.REASUROR IS 'Reasürans şirketi';

-- ANLASMA : Reasürans anlaşması
CREATE TABLE SGR.ANLASMA
(
  ANLASMA_NO               NUMBER(12,0) NOT NULL,
  ANLASMA_TIP              CHAR(1 CHAR) NOT NULL,
  BRANS_KOD                VARCHAR2(10 CHAR),
  BASLANGIC_TAR            DATE NOT NULL,
  BITIS_TAR                DATE NOT NULL,
  SAKLAMA_TUTAR            NUMBER(18,2),
  KAYIT_TAR                DATE DEFAULT SYSDATE NOT NULL,
  KAYIT_KULLANICI          VARCHAR2(30 CHAR),
  GUNCELLEME_TAR           DATE
)
TABLESPACE TS_SGR_DATA;
ALTER TABLE SGR.ANLASMA ADD CONSTRAINT ANLASMA_PK PRIMARY KEY (ANLASMA_NO) USING INDEX TABLESPACE TS_SGR_IDX;
COMMENT ON TABLE SGR.ANLASMA IS 'Reasürans anlaşması';

-- ANLASMA_PAY
CREATE TABLE SGR.ANLASMA_PAY
(
  ANLASMA_NO               NUMBER(12,0) NOT NULL,
  REASUROR_KOD             VARCHAR2(10 CHAR) NOT NULL,
  PAY_ORAN                 NUMBER(9,6) NOT NULL,
  KAYIT_TAR                DATE DEFAULT SYSDATE NOT NULL,
  KAYIT_KULLANICI          VARCHAR2(30 CHAR),
  GUNCELLEME_TAR           DATE
)
TABLESPACE TS_SGR_DATA;
ALTER TABLE SGR.ANLASMA_PAY ADD CONSTRAINT ANLASMA_PAY_PK PRIMARY KEY (ANLASMA_NO, REASUROR_KOD) USING INDEX TABLESPACE TS_SGR_IDX;

-- CESSION : Poliçe bazında devir
CREATE TABLE SGR.CESSION
(
  CESSION_NO               NUMBER(12,0) NOT NULL,
  POLICE_NO                NUMBER(12,0) NOT NULL,
  ANLASMA_NO               NUMBER(12,0) NOT NULL,
  DEVIR_PRIM               NUMBER(18,2),
  DEVIR_TAR                DATE,
  KAYIT_TAR                DATE DEFAULT SYSDATE NOT NULL,
  KAYIT_KULLANICI          VARCHAR2(30 CHAR),
  GUNCELLEME_TAR           DATE
)
TABLESPACE TS_SGR_DATA;
ALTER TABLE SGR.CESSION ADD CONSTRAINT CESSION_PK PRIMARY KEY (CESSION_NO) USING INDEX TABLESPACE TS_SGR_IDX;
COMMENT ON TABLE SGR.CESSION IS 'Poliçe bazında devir';
