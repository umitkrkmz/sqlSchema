-- URUN modülü tabloları
-- Not: bütünlük uygulama katmanında; veritabanında FK tanımlı değildir.

-- BRANS : Branş (kasko, trafik, konut, sağlık...)
CREATE TABLE SGR.BRANS
(
  BRANS_KOD                VARCHAR2(10 CHAR) NOT NULL,
  BRANS_ADI                VARCHAR2(250 CHAR) NOT NULL,
  ANA_BRANS_KOD            VARCHAR2(10 CHAR),
  KAYIT_TAR                DATE DEFAULT SYSDATE NOT NULL,
  KAYIT_KULLANICI          VARCHAR2(30 CHAR),
  GUNCELLEME_TAR           DATE
)
TABLESPACE TS_SGR_DATA;
ALTER TABLE SGR.BRANS ADD CONSTRAINT BRANS_PK PRIMARY KEY (BRANS_KOD) USING INDEX TABLESPACE TS_SGR_IDX;
COMMENT ON TABLE SGR.BRANS IS 'Branş (kasko, trafik, konut, sağlık...)';

-- URUN : Satılan sigorta ürünü
CREATE TABLE SGR.URUN
(
  URUN_KOD                 VARCHAR2(10 CHAR) NOT NULL,
  URUN_ADI                 VARCHAR2(250 CHAR) NOT NULL,
  BRANS_KOD                VARCHAR2(10 CHAR) NOT NULL,
  BASLANGIC_TAR            DATE NOT NULL,
  BITIS_TAR                DATE,
  SATISTA                  CHAR(1 CHAR),
  KAYIT_TAR                DATE DEFAULT SYSDATE NOT NULL,
  KAYIT_KULLANICI          VARCHAR2(30 CHAR),
  GUNCELLEME_TAR           DATE
)
TABLESPACE TS_SGR_DATA;
ALTER TABLE SGR.URUN ADD CONSTRAINT URUN_PK PRIMARY KEY (URUN_KOD) USING INDEX TABLESPACE TS_SGR_IDX;
COMMENT ON TABLE SGR.URUN IS 'Satılan sigorta ürünü';

