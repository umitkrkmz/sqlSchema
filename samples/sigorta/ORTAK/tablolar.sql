-- MUSTERI : Sigorta ettiren, sigortalı ve lehtarlar tek tabloda
CREATE TABLE SGR.MUSTERI
(
  MUSTERI_NO               NUMBER(12,0) NOT NULL,
  MUSTERI_TIP              CHAR(1 CHAR) NOT NULL,
  TCKN                     VARCHAR2(11 CHAR),
  VKN                      VARCHAR2(10 CHAR),
  UNVAN                    VARCHAR2(250 CHAR) NOT NULL,
  DOGUM_TAR                DATE,
  CINSIYET                 CHAR(1 CHAR),
  IL_KOD                   VARCHAR2(10 CHAR),
  ILCE_KOD                 VARCHAR2(10 CHAR),
  ADRES                    VARCHAR2(250 CHAR),
  TEL_NO                   VARCHAR2(20 CHAR),
  EPOSTA                   VARCHAR2(100 CHAR),
  KARA_LISTE               CHAR(1 CHAR),
  KAYIT_TAR                DATE NOT NULL,
  KAYIT_KULLANICI          VARCHAR2(30 CHAR),
  GUNCELLEME_TAR           DATE
)
TABLESPACE TS_SGR_DATA;
ALTER TABLE SGR.MUSTERI ADD CONSTRAINT MUSTERI_PK PRIMARY KEY (MUSTERI_NO) USING INDEX TABLESPACE TS_SGR_IDX;
COMMENT ON TABLE SGR.MUSTERI IS 'Sigorta ettiren, sigortalı ve lehtarlar tek tabloda';
COMMENT ON COLUMN SGR.MUSTERI.MUSTERI_TIP IS 'G = Gerçek kişi, T = Tüzel kişi';
COMMENT ON COLUMN SGR.MUSTERI.CINSIYET IS 'E: Erkek; K: Kadın; B: Belirtilmemiş';
COMMENT ON COLUMN SGR.MUSTERI.KARA_LISTE IS 'Sahtecilik şüphesi. E-Evet / H-Hayır';

