-- ORTAK modülü tabloları
-- Not: bütünlük uygulama katmanında; veritabanında FK tanımlı değildir.

-- IL : İl tanımları
CREATE TABLE SGR.IL
(
  IL_KOD                   VARCHAR2(3 CHAR) NOT NULL,
  IL_ADI                   VARCHAR2(250 CHAR) NOT NULL,
  PLAKA                    VARCHAR2(2 CHAR),
  KAYIT_TAR                DATE DEFAULT SYSDATE NOT NULL,
  KAYIT_KULLANICI          VARCHAR2(30 CHAR),
  GUNCELLEME_TAR           DATE
)
TABLESPACE TS_SGR_DATA;
ALTER TABLE SGR.IL ADD CONSTRAINT IL_PK PRIMARY KEY (IL_KOD) USING INDEX TABLESPACE TS_SGR_IDX;
COMMENT ON TABLE SGR.IL IS 'İl tanımları';

