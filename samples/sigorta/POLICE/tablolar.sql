-- POLICE modülü tabloları
-- Not: bütünlük uygulama katmanında; veritabanında FK tanımlı değildir.

-- TEKLIF : Poliçe teklifi
CREATE TABLE SGR.TEKLIF
(
  TEKLIF_NO                NUMBER(12,0) NOT NULL,
  MUSTERI_NO               NUMBER(12,0) NOT NULL,
  URUN_KOD                 VARCHAR2(10 CHAR) NOT NULL,
  ACENTE_KOD               VARCHAR2(10 CHAR),
  TEKLIF_TAR               DATE NOT NULL,
  GECERLILIK_TAR           DATE,
  BRUT_PRIM                NUMBER(18,2),
  DURUM_KOD                VARCHAR2(10 CHAR),
  KAYIT_TAR                DATE DEFAULT SYSDATE NOT NULL,
  KAYIT_KULLANICI          VARCHAR2(30 CHAR),
  GUNCELLEME_TAR           DATE
)
TABLESPACE TS_SGR_DATA;
ALTER TABLE SGR.TEKLIF ADD CONSTRAINT TEKLIF_PK PRIMARY KEY (TEKLIF_NO) USING INDEX TABLESPACE TS_SGR_IDX;
COMMENT ON TABLE SGR.TEKLIF IS 'Poliçe teklifi';
COMMENT ON COLUMN SGR.TEKLIF.DURUM_KOD IS 'Teklif durumu. @ref KOD_TABLO.KOD (KOD_TIP = ''TEKLIF_DURUM'')';

-- POLICE : Poliçe ana kaydı
CREATE TABLE SGR.POLICE
(
  POLICE_NO                NUMBER(12,0) NOT NULL,
  YENILEME_NO              NUMBER(3,0) NOT NULL,
  TEKLIF_NO                NUMBER(12,0),
  URUN_KOD                 VARCHAR2(10 CHAR) NOT NULL,
  SIGORTA_ETTIREN_NO       NUMBER(12,0) NOT NULL,
  MUSTERI_NO               NUMBER(12,0) NOT NULL,
  ACENTE_KOD               VARCHAR2(10 CHAR),
  BROKER_KOD               VARCHAR2(10 CHAR),
  TANZIM_TAR               DATE NOT NULL,
  BASLANGIC_TAR            DATE NOT NULL,
  BITIS_TAR                DATE NOT NULL,
  DOVIZ_KOD                VARCHAR2(3 CHAR),
  NET_PRIM                 NUMBER(18,2),
  BRUT_PRIM                NUMBER(18,2),
  POLICE_DURUM             CHAR(1 CHAR) NOT NULL,
  ONCEKI_POLICE_NO         NUMBER(12,0),
  KAYIT_TAR                DATE DEFAULT SYSDATE NOT NULL,
  KAYIT_KULLANICI          VARCHAR2(30 CHAR),
  GUNCELLEME_TAR           DATE
)
TABLESPACE TS_SGR_DATA;
ALTER TABLE SGR.POLICE ADD CONSTRAINT POLICE_PK PRIMARY KEY (POLICE_NO) USING INDEX TABLESPACE TS_SGR_IDX;
COMMENT ON TABLE SGR.POLICE IS 'Poliçe ana kaydı';
COMMENT ON COLUMN SGR.POLICE.POLICE_DURUM IS 'Poliçe durumu. @ref KOD_TABLO.KOD (KOD_TIP = ''POLICE_DURUM'')';

-- POLICE_ZEYL : Zeyilname (poliçe değişikliği)
CREATE TABLE SGR.POLICE_ZEYL
(
  POLICE_NO                NUMBER(12,0) NOT NULL,
  ZEYL_NO                  NUMBER(4,0) NOT NULL,
  ZEYL_TIP                 CHAR(1 CHAR) NOT NULL,
  ZEYL_TAR                 DATE NOT NULL,
  PRIM_FARKI_TUTAR         NUMBER(18,2),
  ACIKLAMA                 VARCHAR2(250 CHAR),
  KAYIT_TAR                DATE DEFAULT SYSDATE NOT NULL,
  KAYIT_KULLANICI          VARCHAR2(30 CHAR),
  GUNCELLEME_TAR           DATE
)
TABLESPACE TS_SGR_DATA;
ALTER TABLE SGR.POLICE_ZEYL ADD CONSTRAINT POLICE_ZEYL_PK PRIMARY KEY (POLICE_NO, ZEYL_NO) USING INDEX TABLESPACE TS_SGR_IDX;
COMMENT ON TABLE SGR.POLICE_ZEYL IS 'Zeyilname (poliçe değişikliği)';
COMMENT ON COLUMN SGR.POLICE_ZEYL.ZEYL_TIP IS 'Zeyilname tipi (1=Teminat ekleme, 2=Teminat çıkarma, 3=Bilgi değişikliği, 4=İptal)';

